"""Converts rendered island layers to WebP resources and generates the app's layout table.

    python3 tools/art/export_layers.py build/art/layers
Writes app/src/main/res/drawable-nodpi/isl_*.webp and
app/src/main/kotlin/com/nexus/app/ui/art/IslandLayout.kt (generated — do not edit by hand).
"""
import json, os, sys
from PIL import Image
src = sys.argv[1]
res_dir = "app/src/main/res/drawable-nodpi"
kt = "app/src/main/kotlin/com/nexus/app/ui/art/IslandLayout.kt"
m = json.load(open(os.path.join(src, "layers.json")))
L = m["layers"]
T = m.get("trees")
# Composition frame: union of every layer *and* a full-grown tree on every grove slot, so tall towers,
# ancient canopies and glow halos are never clipped.
boxes = [v["box"] for v in L.values()]
if T:
    for st in T["stages"].values():
        w, h = st["box"][2] - st["box"][0], st["box"][3] - st["box"][1]
        for sl in T["slots"]:
            x0 = sl["px"][0] - st["anchor"][0]; y0 = sl["px"][1] - st["anchor"][1]
            boxes.append([x0, y0, x0 + w, y0 + h])
fl = int(min(b[0] for b in boxes)); ft = int(min(b[1] for b in boxes))
fr = int(max(b[2] for b in boxes)) + 1; fb = int(max(b[3] for b in boxes)) + 1
fw, fh = fr - fl, fb - ft
os.makedirs(res_dir, exist_ok=True); os.makedirs(os.path.dirname(kt), exist_ok=True)
total = 0
rows = []
for name in sorted(L):
    v = L[name]; l, t, r, b = v["box"]
    out = os.path.join(res_dir, f"isl_{name}.webp")
    Image.open(os.path.join(src, name + ".png")).save(out, "WEBP", quality=86, method=6)
    total += os.path.getsize(out)
    depth = v["depth"] if v["depth"] < 1e8 else 1e6
    rows.append(f'        "{name}" to IslandLayer(R.drawable.isl_{name}, {(l - fl) / fw:.5f}f, {(t - ft) / fh:.5f}f, {(r - l) / fw:.5f}f, {(b - t) / fh:.5f}f, {depth:.4f}f),')
tree_rows, slot_rows = [], []
if T:
    for name in ["seed", "sprout", "young", "mature", "ancient"]:
        st = T["stages"][name]; w, h = st["box"][2] - st["box"][0], st["box"][3] - st["box"][1]
        out = os.path.join(res_dir, f"isl_tree_{name}.webp")
        Image.open(os.path.join(src, f"tree_{name}.png")).save(out, "WEBP", quality=88, method=6); total += os.path.getsize(out)
        tree_rows.append(f"        TreeArt(R.drawable.isl_tree_{name}, {w / fw:.5f}f, {h / fh:.5f}f, {st['anchor'][0] / w:.5f}f, {st['anchor'][1] / h:.5f}f),")
    for sl in T["slots"]:
        slot_rows.append(f"        TreeSlot({(sl['px'][0] - fl) / fw:.5f}f, {(sl['px'][1] - ft) / fh:.5f}f, {sl['depth']:.4f}f),")
code = f'''// GENERATED by tools/art/export_layers.py from the Blender layer renders. Do not edit by hand.
package com.nexus.app.ui.art

import com.nexus.app.R

/**
 * One pre-rendered island layer. Position and size are fractions of the composition frame
 * ({fw}×{fh} px at render scale). [depth] is the camera distance: larger = further = drawn first.
 */
data class IslandLayer(val res: Int, val x: Float, val y: Float, val w: Float, val h: Float, val depth: Float)

/** A tree sprite: size as frame fractions, anchor (ground point) as fractions of the sprite. */
data class TreeArt(val res: Int, val w: Float, val h: Float, val anchorX: Float, val anchorY: Float)

/** A grove slot: ground point as frame fractions + camera depth. */
data class TreeSlot(val x: Float, val y: Float, val depth: Float)

object IslandLayout {{
    /** Width / height of the composition frame. */
    const val ASPECT = {fw / fh:.5f}f
    val layers: Map<String, IslandLayer> = mapOf(
{chr(10).join(rows)}
    )
    /** Seed, Sprout, Young Tree, Mature Tree, Ancient Tree. */
    val trees: List<TreeArt> = listOf(
{chr(10).join(tree_rows)}
    )
    /** Grove slots in planting order. */
    val treeSlots: List<TreeSlot> = listOf(
{chr(10).join(slot_rows)}
    )
}}
'''
open(kt, "w").write(code)
print(f"{len(L)} layers, {total // 1024} KB, frame {fw}x{fh}")
