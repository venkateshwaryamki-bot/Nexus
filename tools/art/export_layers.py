"""Converts rendered island layers to WebP resources and generates the app's layout table.

    python3 tools/art/export_layers.py build/art/layers
Writes app/src/main/res/drawable-nodpi/isl_*.webp and
app/src/main/kotlin/com/nexus/app/ui/art/IslandLayout.kt (generated — do not edit by hand).
"""
import json, os, sys
from PIL import Image
src = sys.argv[1]
res_dir = "app/src/main/res/drawable-nodpi"
kt = "app/src/main/kotlin/com/nexus/app/ui/art/IslandLayout.kt"
m = json.load(open(os.path.join(src, "layers.json")))
L = m["layers"]
# Composition frame: union of every layer, so tall towers and glow halos are never clipped.
fl = min(v["box"][0] for v in L.values()); ft = min(v["box"][1] for v in L.values())
fr = max(v["box"][2] for v in L.values()); fb = max(v["box"][3] for v in L.values())
fw, fh = fr - fl, fb - ft
os.makedirs(res_dir, exist_ok=True); os.makedirs(os.path.dirname(kt), exist_ok=True)
total = 0
rows = []
for name in sorted(L):
    v = L[name]; l, t, r, b = v["box"]
    out = os.path.join(res_dir, f"isl_{name}.webp")
    Image.open(os.path.join(src, name + ".png")).save(out, "WEBP", quality=86, method=6)
    total += os.path.getsize(out)
    depth = v["depth"] if v["depth"] < 1e8 else 1e6
    rows.append(f'        "{name}" to IslandLayer(R.drawable.isl_{name}, {(l - fl) / fw:.5f}f, {(t - ft) / fh:.5f}f, {(r - l) / fw:.5f}f, {(b - t) / fh:.5f}f, {depth:.4f}f),')
code = f'''// GENERATED by tools/art/export_layers.py from the Blender layer renders. Do not edit by hand.
package com.nexus.app.ui.art

import com.nexus.app.R

/**
 * One pre-rendered island layer. Position and size are fractions of the composition frame
 * ({fw}×{fh} px at render scale). [depth] is the camera distance: larger = further = drawn first.
 */
data class IslandLayer(val res: Int, val x: Float, val y: Float, val w: Float, val h: Float, val depth: Float)

object IslandLayout {{
    /** Width / height of the composition frame. */
    const val ASPECT = {fw / fh:.5f}f
    val layers: Map<String, IslandLayer> = mapOf(
{chr(10).join(rows)}
    )
}}
'''
open(kt, "w").write(code)
print(f"{len(L)} layers, {total // 1024} KB, frame {fw}x{fh}")
